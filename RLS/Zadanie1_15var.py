# Практическая работа №1. Вариант 15
# Расчёт порога обнаружения сигнала и вероятности правильного обнаружения
# для двух случаев: полностью известный сигнал и случайная начальная фаза.

import math
import mpmath as mp

mp.mp.dps = 40  # высокая точность

# ------------------------------
# Исходные данные
# ------------------------------
# Задача 1
qP1_db = 3.9
F1 = 0.043

# Задача 2
qP2_db = 5.8
F2 = 0.073
A = 5.3       # В
tau_ms = 31   # мс

# ------------------------------
# Вспомогательные функции
# ------------------------------
def Phi(x):
    """Функция Лапласа (CDF нормального распределения)."""
    return 0.5 * (1 + mp.erf(x / mp.sqrt(2)))

def Phi_inv(p):
    """Обратная функция Лапласа (обратная к Φ)."""
    return mp.sqrt(2) * mp.erfinv(2*p - 1)

# ------------------------------
# Задача 1. Полностью известный сигнал
# ------------------------------
print("Задача 1 — полностью известный сигнал на фоне АГШ\n")

# А) Перевод qP из дБ в разы
qP1_lin = 10 ** (qP1_db / 10)
print(f"А) qP = 10^({qP1_db}/10) = {qP1_lin:.3f} раз.")

# Б) Пересчёт в отношение по напряжению
qU1 = math.sqrt(qP1_lin)
print(f"Б) qU = √(qP) = {qU1:.3f} раза.")

# В) Расчёт порога и вероятности обнаружения
Phi_inv_1 = float(Phi_inv(1 - F1))
z_p_1 = qU1 * Phi_inv_1
D1 = float(Phi(qU1 - Phi_inv_1))
print("В) Порог и вероятность обнаружения:")
print(f"   Φ⁻¹(1 − F) = {Phi_inv_1:.3f}")
print(f"   zп = qU * Φ⁻¹(1 − F) = {qU1:.3f} * {Phi_inv_1:.3f} = {z_p_1:.3f}")
print(f"   D = Φ(qU − Φ⁻¹(1 − F)) = {D1:.3f}\n")
print(f"Ответ (задача 1): zп = {z_p_1:.3f}, D = {D1:.3f}\n")

# ------------------------------
# Задача 2. Случайная начальная фаза
# ------------------------------
print("Задача 2 — случайная начальная фаза (некогерентный детектор)\n")

# А) Перевод qP из дБ в разы
qP2_lin = 10 ** (qP2_db / 10)
print(f"А) qP = 10^({qP2_db}/10) = {qP2_lin:.3f} раз.")

# Б) Пересчёт в qU
qU2 = math.sqrt(qP2_lin)
print(f"Б) qU = √(qP) = {qU2:.3f} раза.")

# В) Энергия полезного сигнала
tau_s = tau_ms * 1e-3
Es = 2 * (A ** 2) * tau_s
print(f"В) Энергия сигнала Es = 2 * A² * τ = 2 * {A}² * {tau_s:.3f} = {Es:.3f} Вт·с.")

# Г) Расчёт σ, zп и D
sigma = math.sqrt(Es) / qU2
z_thresh = sigma * math.sqrt(-2 * math.log(F2))
nu = math.sqrt(2 * Es) / sigma

# Интеграл (Marcum-Q)
def integrand(r):
    return r * mp.e ** (-(r**2 + nu**2)/2) * mp.besseli(0, nu * r)

z_norm = z_thresh / sigma
D2 = float(mp.quad(lambda rr: integrand(rr), [z_norm, mp.inf]))

print("Г) Порог и вероятность обнаружения:")
print(f"   σ = √(Es)/qU = {sigma:.3f}")
print(f"   zп = σ * √(−2 ln F) = {z_thresh:.3f}")
print(f"   ν = √(2Es)/σ = {nu:.3f}")
print(f"   D = {D2:.3f}\n")
print(f"Ответ (задача 2): zп = {z_thresh:.3f}, D = {D2:.3f}\n")

# ------------------------------
# Итог
# ------------------------------
print(f"Окончательный ответ: а) zп = {z_p_1:.3f}, D = {D1:.3f}; б) zп = {z_thresh:.3f}, D = {D2:.3f}")
